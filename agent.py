# ============================================================
# Agent runner
# ============================================================

def run_agent(message: str, history: str = "") -> dict:
    config: RunnableConfig = {
        "configurable": {
            "thread_id": "1"
        }
    }

    state = chat.invoke(
        {
            "input": message,
            "history": history,
            "retrieval_results": [],
            "context": "",
            "output": "",
        },
        config,
    )

    context_text = state.get("context", "") or ""

    return {
        "reply": state.get("output", ""),
        "context_used": {
            "query": message,
            "context": context_text,
            "context_len": len(context_text) / 4 if context_text else 0,
        },
        "history": history,
    }


if __name__ == "__main__":
    example_message = (
        "What is my attendance and who is the CSE HOD? "
        "what are the current events happening this week?"
    )

    print(run_agent(example_message)["reply"])
